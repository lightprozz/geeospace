import { expect, test } from "@playwright/test";

test("OS shell: desktop windows or mobile Home, launcher, search and appearance", async ({ page, request, isMobile }) => {
  expect(await (await request.get("/api/health")).json()).toMatchObject({ service: "geeospace" });
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto("/");
  const root = page.locator(".geeospace-os");
  await expect(root).toHaveAttribute("data-ready", "true");
  await page.screenshot({ path: test.info().outputPath("os-home.png"), fullPage: true });
  if (isMobile) {
    const home = page.getByRole("navigation", { name: "Ứng dụng trên điện thoại" });
    await expect(home).toBeVisible();
    await home.getByRole("button", { name: "Yêu cầu của tôi", exact: true }).click();
    const win = page.locator('[data-app="requests"]');
    await expect(win.getByRole("heading", { name: "Yêu cầu của tôi", exact: true })).toBeVisible();
    await win.getByRole("button", { name: "Về màn hình chính" }).click();
    await expect(home).toBeVisible();
    await home.getByRole("button", { name: "Giao diện", exact: true }).click();
  } else {
    const dock = page.getByRole("navigation", { name: "Dock ứng dụng" });
    await expect(dock).toBeVisible();
    await expect(page.locator('[data-app="today"]')).toBeVisible();
    await expect(page.locator('[data-app="assistant"]')).toBeVisible();
    await dock.getByRole("button", { name: "Yêu cầu của tôi", exact: true }).click();
    const win = page.locator('[data-app="requests"]');
    await expect(win).toHaveAttribute("data-phase", "visible");
    const original = (await win.boundingBox())!;
    const title = (await win.locator(".os-window-name").boundingBox())!;
    await page.mouse.move(title.x + title.width / 2, title.y + title.height / 2);
    await page.mouse.down(); await page.mouse.move(title.x + title.width / 2 + 65, title.y + title.height / 2 + 35, { steps: 6 }); await page.mouse.up();
    await expect.poll(async () => (await win.boundingBox())!.x).toBeGreaterThan(original.x + 50);
    const moved = (await win.boundingBox())!;
    const corner = (await win.getByRole("button", { name: "Đổi kích thước Yêu cầu của tôi se", exact: true }).boundingBox())!;
    await page.mouse.move(corner.x + 7, corner.y + 7); await page.mouse.down(); await page.mouse.move(corner.x + 57, corner.y + 22, { steps: 5 }); await page.mouse.up();
    await expect.poll(async () => (await win.boundingBox())!.width).toBeGreaterThan(moved.width + 35);
    const beforeKeyboard = (await win.boundingBox())!;
    await win.getByRole("button", { name: "Đổi kích thước Yêu cầu của tôi w", exact: true }).focus();
    await page.keyboard.press("ArrowRight");
    await expect.poll(async () => (await win.boundingBox())!.x).toBeGreaterThan(beforeKeyboard.x + 10);
    await expect(win).toHaveAttribute("data-phase", "visible");
    const beforeNorth = (await win.boundingBox())!;
    await win.getByRole("button", { name: "Đổi kích thước Yêu cầu của tôi n", exact: true }).focus();
    await page.keyboard.press("Shift+ArrowUp");
    await expect.poll(async () => (await win.boundingBox())!.y).toBeLessThan(beforeNorth.y - 30);
    await win.getByRole("button", { name: "Thu nhỏ Yêu cầu của tôi", exact: true }).click();
    await expect(win).toBeHidden();
    await dock.getByRole("button", { name: "Yêu cầu của tôi", exact: true }).click();
    await expect(win).toBeVisible();
    await win.getByRole("button", { name: "Phóng to hoặc khôi phục Yêu cầu của tôi" }).click();
    await expect(win).toHaveAttribute("data-mode", "maximized");
    await win.getByRole("button", { name: "Phóng to hoặc khôi phục Yêu cầu của tôi" }).click();
    await expect(win).toHaveAttribute("data-mode", "normal");
    await page.keyboard.press("Alt+ArrowRight");
    await expect(win).toHaveAttribute("data-mode", "right");
    await dock.getByRole("button", { name: "Xem tất cả cửa sổ" }).click();
    await expect(page.getByRole("dialog", { name: "Tất cả cửa sổ", exact: true })).toBeVisible();
    await page.screenshot({ path: test.info().outputPath("os-overview.png"), fullPage: true });
    await page.getByRole("button", { name: "Chuyển đến Yêu cầu của tôi" }).click();
    await expect(win).toHaveClass(/is-focused/);
    await dock.getByRole("button", { name: "Tất cả ứng dụng", exact: true }).click();
    const launcher = page.getByRole("dialog", { name: "Tất cả ứng dụng", exact: true });
    await expect(launcher).toBeVisible();
    await launcher.getByRole("combobox", { name: "Tìm ứng dụng" }).fill("lop");
    await launcher.getByRole("option", { name: "Lớp & giảng dạy", exact: true }).click();
    await expect(page.locator('[data-app="lms"]')).toBeVisible();
    await dock.getByRole("button", { name: "Giao diện", exact: true }).click();
  }
  const appearance = page.locator('[data-app="appearance"]');
  await appearance.getByRole("button", { name: "Sáng", exact: true }).click();
  await expect(root).toHaveAttribute("data-theme", "light");
  await appearance.getByRole("button", { name: "Hình nền Đại dương", exact: true }).click();
  await expect(root).toHaveAttribute("data-wallpaper", "ocean");
  await expect.poll(() => page.evaluate(() => localStorage.getItem("geeospace.desktop.appearance.v1"))).toContain('"ocean"');
  await page.reload();
  await expect(root).toHaveAttribute("data-ready", "true");
  await expect(root).toHaveAttribute("data-theme", "light");
  await expect(root).toHaveAttribute("data-wallpaper", "ocean");
  await page.keyboard.press("Control+k");
  const search = page.getByRole("dialog", { name: "Tìm nhanh chức năng", exact: true });
  await search.getByRole("combobox", { name: "Tìm ứng dụng" }).fill("tu hoc");
  await expect(search.getByRole("option", { name: /Tự học/ })).toHaveAttribute("aria-selected", "true");
  await expect(search.getByRole("combobox", { name: "Tìm ứng dụng" })).toHaveAttribute("aria-activedescendant", /learning$/);
  await page.keyboard.press("Enter");
  await expect(page.locator('[data-app="learning"]')).toBeVisible();
  if (isMobile) {
    await expect(page.locator('[data-app="learning"]')).toHaveAttribute("data-phase", "visible");
    const title = (await page.locator('[data-app="learning"] .os-window-name').boundingBox())!;
    await page.mouse.move(title.x + title.width / 2, title.y + title.height / 2);
    await page.mouse.down(); await page.mouse.move(title.x + title.width / 2, title.y + title.height / 2 + 140, { steps: 8 }); await page.mouse.up();
    await expect(page.locator('[data-app="learning"]')).toBeHidden();
    await page.goForward();
    await expect(page.locator('[data-app="learning"]')).toBeVisible();
    await page.goBack();
    await expect(page.locator('[data-app="learning"]')).toBeHidden();
    await page.goForward();
    await expect(page.locator('[data-app="learning"]')).toBeVisible();
    await page.setViewportSize({ width: 1024, height: 900 });
    await expect(page.locator('[data-app="learning"]')).toBeVisible();
    await expect(page.locator('[data-app="learning"]')).toHaveClass(/is-focused/);
    await page.setViewportSize({ width: 320, height: 812 });
    for (const entry of ["/requests", "/#requests"]) {
      await page.goto("/work");
      await page.goto(entry);
      await expect(root).toHaveAttribute("data-ready", "true");
      await page.getByRole("banner").getByRole("button", { name: "Tài khoản Gee-O", exact: true }).click();
      await page.locator('[data-app="account"]').getByRole("button", { name: "Về màn hình chính" }).click();
      await expect(page).toHaveURL(/\/$/);
      await expect(page.getByRole("navigation", { name: "Ứng dụng trên điện thoại" })).toBeVisible();
    }
  }
  await page.screenshot({ path: test.info().outputPath("os-app.png"), fullPage: true });
  expect(errors).toEqual([]);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});

test("OS persistence: minimize survives reload and mobile Home preserves the desktop layout", async ({ page, isMobile }) => {
  test.skip(isMobile, "This regression starts with a desktop layout and crosses to phone.");
  await page.goto("/");
  await expect(page.locator(".geeospace-os")).toHaveAttribute("data-ready", "true");
  const dock = page.getByRole("navigation", { name: "Dock ứng dụng" });
  await dock.getByRole("button", { name: "Yêu cầu của tôi", exact: true }).click();
  const win = page.locator('[data-app="requests"]');
  await win.getByRole("button", { name: "Thu nhỏ Yêu cầu của tôi" }).click();
  await expect(page).not.toHaveURL(/#requests$/);
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem("geeospace.desktop.layout.v1") ?? "{}").windows?.requests?.minimized)).toBe(true);
  await page.reload();
  await expect(page.locator(".geeospace-os")).toHaveAttribute("data-ready", "true");
  await expect(win).toBeHidden();
  const saved = await page.evaluate(() => localStorage.getItem("geeospace.desktop.layout.v1"));
  await page.setViewportSize({ width: 375, height: 812 });
  await page.goto("/");
  await expect(page.getByRole("navigation", { name: "Ứng dụng trên điện thoại" })).toBeVisible();
  expect(await page.evaluate(() => localStorage.getItem("geeospace.desktop.layout.v1"))).toBe(saved);
  await page.getByRole("navigation", { name: "Ứng dụng trên điện thoại" }).getByRole("button", { name: "Yêu cầu của tôi", exact: true }).click();
  await page.setViewportSize({ width: 1200, height: 900 });
  await expect(win).toBeVisible();
  await expect(win).toHaveClass(/is-focused/);
  await expect(page).toHaveURL(/#requests$/);
});
